// Regenerates web/icons.js from a local copy of Lucide (https://lucide.dev, ISC licence).
// Usage: node tools/make-icons.mjs <path to lucide/dist/esm/icons>
// The icon files are read as text and parsed; nothing from them is executed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const NAMES = [
  'pencil', 'eraser', 'paintbrush', 'paint-bucket', 'pipette', 'square', 'slash', 'move', 'rotate-3d', 'hand',
  'eye', 'eye-off', 'lock', 'lock-open', 'undo-2', 'redo-2', 'plus', 'minus', 'play', 'pause', 'layers', 'copy',
  'merge', 'trash', 'download', 'bot', 'scan-eye', 'box', 'grid-3x3', 'chevron-down', 'chevron-right', 'palette',
  'square-split-horizontal', 'square-split-vertical', 'ghost', 'image', 'folder-open', 'save', 'x', 'check', 'film', 'cuboid',
  'focus', 'zoom-in', 'zoom-out', 'file-plus', 'square-dashed', 'blend', 'arrow-up-down', 'frame', 'sparkles', 'clock', 'search', 'ellipsis', 'house', 'info', 'plug', 'external-link', 'terminal',
  'folder', 'folders', 'folder-plus', 'folder-input', 'archive', 'archive-restore', 'trash-2', 'sparkle', 'github', 'layout-grid', 'list', 'arrow-up', 'arrow-down', 'panel-left', 'history',
];

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/make-icons.mjs <lucide/dist/esm/icons>'); process.exit(1); }
const icons = {};
const missing = [];
for (const name of NAMES) {
  const file = path.join(dir, `${name}.mjs`);
  if (!fs.existsSync(file)) { missing.push(name); continue; }
  const text = fs.readFileSync(file, 'utf8');
  const nodes = [];
  for (const m of text.matchAll(/\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/"?([\w-]+)"?\s*:\s*"([^"]*)"/g)) attrs[a[1]] = a[2];
    nodes.push([m[1], attrs]);
  }
  icons[name] = nodes;
}
if (missing.length) { console.error('missing icons: ' + missing.join(', ')); process.exit(1); }

const here = path.dirname(fileURLToPath(import.meta.url));
const out = `/* Icons from Lucide (https://lucide.dev), ISC licence — see web/LUCIDE-LICENSE.txt.
   Generated by tools/make-icons.mjs; do not edit by hand. */
window.LUCIDE = ${JSON.stringify(icons)};
`;
fs.writeFileSync(path.join(here, '..', 'web', 'icons.js'), out);
console.log(`wrote ${Object.keys(icons).length} icons`);
