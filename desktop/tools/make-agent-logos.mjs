// Regenerates src/lib/agent-logo-data.ts from the SVG files in assets/agent-logos (logos from
// @lobehub/icons-static-svg, MIT; see src/lib/AGENT-LOGOS-ATTRIBUTION.txt). Those files are the source: to add or
// change a logo, change the SVG and run this. The page inlines the logos, so single-colour ones follow the theme's
// text colour and nothing is fetched at run time.
//
//   node tools/make-agent-logos.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const desktop = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(desktop, 'assets', 'agent-logos');
const logos = {};
for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.svg')).sort()) {
  let svg = fs.readFileSync(path.join(dir, f), 'utf8').trim();
  // Size comes from CSS; drop the fixed 1em size, inline styles and titles.
  svg = svg.replace(/\s(width|height)="1em"/g, '').replace(/\sstyle="[^"]*"/, '').replace(/<title>.*?<\/title>/s, '');
  // The page puts these strings into the document as markup (TrustedSvg): nothing in them may run.
  if (!svg.startsWith('<svg') || /<script|on\w+=/i.test(svg)) throw new Error(`unexpected content in ${f}`);
  logos[f.replace(/\.svg$/, '')] = svg;
}
const out = `/* Agent logos from @lobehub/icons-static-svg (MIT): see AGENT-LOGOS-ATTRIBUTION.txt next to this file.
   Generated by desktop/tools/make-agent-logos.mjs from desktop/assets/agent-logos; do not edit by hand. */
export const AGENT_LOGOS: Record<string, string> = {
${Object.entries(logos).map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`).join('\n')}
};
`;
fs.writeFileSync(path.join(desktop, 'src', 'lib', 'agent-logo-data.ts'), out);
console.log(`wrote ${Object.keys(logos).length} logos to src/lib/agent-logo-data.ts`);
