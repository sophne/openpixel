// Regenerates web/agent-logos.js from the SVG files in web/agents (logos from @lobehub/icons-static-svg, MIT;
// see web/agents/ATTRIBUTION.txt). The page inlines them: WebKit refuses CSS masks from local files, and inline
// SVG lets single-colour logos follow the theme's text colour.
// Usage: node tools/make-agent-logos.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const web = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'web');
const dir = path.join(web, 'agents');
const logos = {};
for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.svg')).sort()) {
  let svg = fs.readFileSync(path.join(dir, f), 'utf8').trim();
  // Size comes from CSS; drop the fixed 1em size, inline styles and titles.
  svg = svg.replace(/\s(width|height)="1em"/g, '').replace(/\sstyle="[^"]*"/, '').replace(/<title>.*?<\/title>/s, '');
  if (!svg.startsWith('<svg') || /<script|on\w+=/i.test(svg)) throw new Error(`unexpected content in ${f}`);
  logos[f.replace(/\.svg$/, '')] = svg;
}
fs.writeFileSync(path.join(web, 'agent-logos.js'),
  `/* Agent logos from @lobehub/icons-static-svg (MIT) — see web/agents/ATTRIBUTION.txt.\n   Generated by tools/make-agent-logos.mjs; do not edit by hand. */\nwindow.AGENT_LOGOS = ${JSON.stringify(logos)};\n`);
console.log(`wrote ${Object.keys(logos).length} logos`);
